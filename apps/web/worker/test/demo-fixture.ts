export const DEMO_EDIT_COMMAND = [
  "set -e",
  "mkdir -p src test",
  "cat > src/retry.js <<'EOF'",
  "/**",
  " * Run `attempt` until it succeeds or the budget is spent.",
  " *",
  " * The budget counts attempts rather than retries, so a budget of 1 means",
  ' * "try once and do not retry". A budget below 1 is a programming error, not',
  " * a silent no-op, so it throws here instead of returning undefined later.",
  " */",
  "export async function withRetryBudget(attempt, budget = 3) {",
  "  if (!Number.isInteger(budget) || budget < 1) {",
  '    throw new RangeError("retry budget must be a positive integer");',
  "  }",
  "  let lastError;",
  "  for (let tries = 0; tries < budget; tries += 1) {",
  "    try {",
  "      return await attempt(tries);",
  "    } catch (error) {",
  "      lastError = error;",
  "    }",
  "  }",
  "  throw lastError;",
  "}",
  "EOF",
  "cat > src/widgets.js <<'EOF'",
  "export function widgetCount(widgets) {",
  "  if (!Array.isArray(widgets)) {",
  "    return 0;",
  "  }",
  "  return widgets.length;",
  "}",
  "",
  "export function widgetNames(widgets) {",
  "  if (widgetCount(widgets) === 0) {",
  "    return [];",
  "  }",
  "  return widgets.map((widget) => String(widget));",
  "}",
  "EOF",
  "cat > test/widgets.test.js <<'EOF'",
  'import assert from "node:assert/strict";',
  'import { test } from "node:test";',
  'import { withRetryBudget } from "../src/retry.js";',
  'import { widgetCount, widgetNames } from "../src/widgets.js";',
  "",
  'test("counts widgets, and tolerates a missing list", () => {',
  '  assert.equal(widgetCount(["a", "b"]), 2);',
  "  assert.equal(widgetCount(undefined), 0);",
  "});",
  "",
  'test("names widgets", () => {',
  '  assert.deepEqual(widgetNames(["a", "b"]), ["a", "b"]);',
  "  assert.deepEqual(widgetNames(undefined), []);",
  "});",
  "",
  'test("retries until the attempt succeeds", async () => {',
  "  let calls = 0;",
  "  const value = await withRetryBudget(() => {",
  "    calls += 1;",
  '    if (calls < 3) throw new Error("not yet");',
  '    return "ready";',
  "  }, 5);",
  '  assert.equal(value, "ready");',
  "  assert.equal(calls, 3);",
  "});",
  "",
  'test("rethrows the last error once the budget is spent", async () => {',
  "  let calls = 0;",
  "  await assert.rejects(",
  "    withRetryBudget(() => {",
  "      calls += 1;",
  '      throw new Error("still failing");',
  "    }, 2),",
  "    /still failing/,",
  "  );",
  "  assert.equal(calls, 2);",
  "});",
  "EOF",
  "cat > README.md <<'EOF'",
  "# widgets",
  "",
  "A small package for counting and naming widgets.",
  "",
  "## Retries",
  "",
  "`withRetryBudget(attempt, budget)` runs `attempt` until it succeeds or the",
  "budget is spent, then rethrows the last error. The budget counts attempts,",
  "so a budget of 1 tries once and does not retry.",
  "EOF",
].join("\n");

